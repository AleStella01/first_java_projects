    public Stampa(String n, String c, String dest, String s, String pag, String mez, String num_c){
       initComponents();
        if(s.compareTo("Maschio")==0){
            if(pag.compareTo("Contanti")==0)
                display1.setText("Il sig. "+c+" "+n+" ha prenotato il viaggio a "+dest+" da effettuare con "+mez+". \nIl pagamento sarà effettuato in contanti.");
            else
                display1.setText("Il sig. "+c+" "+n+" ha prenotato il viaggio a "+dest+" da effettuare con "+mez+". \nIl pagamento sarà effettuato con carta di credito numero "+num_c+".");
        }
        else{
            if(pag.compareTo("Contanti")==0)
                display1.setText("La sig.ra "+c+" "+n+" ha prenotato il viaggio a "+dest+" da effettuare con "+mez+". \nIl pagamento sarà effettuato in contanti.");
            else
                display1.setText("La sig.ra "+c+" "+n+" ha prenotato il viaggio a "+dest+" da effettuare con "+mez+". \nIl pagamento sarà effettuato con carta di credito numero "+num_c+".");
        } 
    }

