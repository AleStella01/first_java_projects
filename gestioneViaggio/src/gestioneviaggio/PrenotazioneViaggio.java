    private void confermaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confermaActionPerformed
        // TODO add your handling code here:
        boolean vuoto = false, avanti = true;
        String dest="", n="", c="",mez="",num_c="",pagamento="";
        char sesso=' ';

        if (destinazione.getSelectedIndex()==0 && mezzo.getSelectedIndex()==0) {
            vuoto = true;
        }

        if (M.isSelected() == false && femmina.isSelected() == false) {
            vuoto = true;
        }

        if (contanti.isSelected() == false && carta.isSelected() == false) {
            vuoto = true;
        }

        if (contanti.isSelected()) {
                pagamento = contanti.getText();
            } else {
                pagamento = carta.getText();
            }
        if(pagamento.compareTo(carta.getText().toString())==0)
            if(num.getText().isEmpty())
                vuoto=true;
        
        if (cognome.getText().isEmpty() || nome.getText().isEmpty() || vuoto == true) {
            JOptionPane.showMessageDialog(this, "Non è possibile effettuale la prenotazione, mancono alcune informazioni", "Errore", JOptionPane.ERROR_MESSAGE);
            avanti = false;
        }

        
        
        if (avanti) {
            n = nome.getText().toString();
            c = cognome.getText().toString();
            num_c = num.getText().toString();
            
            if (M.isSelected()) {
                sesso = M.getText().charAt(0);
            } else {
                sesso = femmina.getText().charAt(0);
            }
            
            dest = destinazione.getSelectedItem().toString();
            mez = mezzo.getSelectedItem().toString();
            //inserire dati in un oggetto di tipo viaggi
            Viaggi viaggio = new Viaggi(c,n,dest,mez,sesso,pagamento,num_c); 
            a.add(viaggio);
        }
    }//GEN-LAST:event_confermaActionPerformed

