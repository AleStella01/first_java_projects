    private void btn_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_loginActionPerformed
        // TODO add your handling code here:
        String nome, parola;
        int i;
        boolean vuoto=false, avanti=true, accesso=true;
        Utente user = null;
        if(txt_user.getText().isEmpty())
            vuoto=true;
        if(psw_password.getText().isEmpty())
            vuoto=true;
        if(vuoto){
            lbl_user.setForeground(Color.red);
            lbl_password.setForeground(Color.red);
            txt_user.setForeground(Color.red);
            psw_password.setForeground(Color.red);
            lbl_esc1.setVisible(true);
            lbl_esc2.setVisible(true);
            avanti=false;
            JOptionPane.showMessageDialog(this, "Devi inserire i dati negli spazi", "Errore", JOptionPane.ERROR_MESSAGE);
        }
        if(avanti){
            
                nome=txt_user.getText();
                parola=psw_password.getText();
                for(i=0;i<password.size() && accesso;i++){
                    user=(Utente)password.get(i);
                    if(nome.equals(user.utente))
                        accesso=false;
                }
                if(accesso){
                    lbl_user.setForeground(Color.red);
                    lbl_password.setForeground(Color.red);
                    txt_user.setForeground(Color.red);
                    psw_password.setForeground(Color.red);
                    lbl_esc1.setVisible(true);
                    lbl_esc2.setVisible(true);
                    avanti=false;
                    JOptionPane.showMessageDialog(this, "L'utente non esiste", "Errore", JOptionPane.ERROR_MESSAGE);
                }else
                    if(user.ruolo.equals("Amministratore")){
                        MenuAmministratore menu = new MenuAmministratore(password,spartiti,strumenti,i-1);
                        menu.setVisible(true);
                        this.dispose();
                    } else 
                        if(user.ruolo.equals("Dipendente")){
                            MenuDipendenti menu = new MenuDipendenti(strumenti,spartiti,password,i-1);
                            menu.setVisible(true);
                            this.dispose();
                        }else
                            if(user.ruolo.equals("Cliente"))
                                JOptionPane.showMessageDialog(this,"Il tuo potere non ti permette di accedere","ahahah",JOptionPane.ERROR_MESSAGE);
            
        }
    }//GEN-LAST:event_btn_loginActionPerformed

