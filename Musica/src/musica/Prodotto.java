    private void btn_registraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_registraActionPerformed
        // TODO add your handling code here:
        boolean vuoto=false, x=false,trovo=false;
        Spartito sp,spar;
        Strumento sr,str;
        String marca,tipo,codice,modello,qual = null,autore,titolo;
        int pezzi = 0, n=0;
        float prezzo = 0;
        if(rbt_strumento.isSelected()==false && rbt_spartito.isSelected()==false){
            lbl_prodotto.setForeground(Color.red);
            JOptionPane.showMessageDialog(this, "Selezionare un item!", "Errore", JOptionPane.ERROR_MESSAGE);
        }else{
            if(rbt_strumento.isSelected()){
                if(txt_modello.getText().isEmpty()){
                    vuoto=true;
                    lbl_modello.setForeground(Color.red);
                }
                if(rbt_nuovo.isSelected()==false && rbt_usato.isSelected()==false){
                    vuoto=true;
                    lbl_qual.setForeground(Color.red);
                }
            }else{
                if(txt_autore.getText().isEmpty()){
                    vuoto=true;
                    lbl_autore.setForeground(Color.red);
                }else{
                    if(ControlliConv.controllanome(txt_autore.getText())){
                        vuoto=true;
                        lbl_autore.setForeground(Color.red);
                    }
                }
                if(txt_titolo.getText().isEmpty()){
                    vuoto=true;
                    lbl_titolo.setForeground(Color.red);
                }else{
                    if(ControlliConv.controllanome(txt_titolo.getText())){
                        vuoto=true;
                        lbl_titolo.setForeground(Color.red);
                    }
                }
            }
            if(txt_marca.getText().isEmpty()){
                vuoto=true;
                lbl_marca.setForeground(Color.red);
            }
            if(cmb_tipo.getSelectedIndex()==0){
                vuoto=true;
                lbl_tipo.setForeground(Color.red);
            }
            if(txt_prezzo.getText().isEmpty()){
                vuoto=true;
                lbl_prezzo.setForeground(Color.red);
            }
            if(txt_codice.getText().isEmpty()){
                vuoto=true;
                lbl_codice.setForeground(Color.red);
            }
            if(cmb_pezzi.getSelectedIndex()==0){
                vuoto=true;
                lbl_pezzi.setForeground(Color.red);
            }
        }
        if(vuoto)
            JOptionPane.showMessageDialog(this, "Impossibile effettuare la registrazione! Mancano dati!", "Errore", JOptionPane.ERROR_MESSAGE);
        else{
            marca=txt_marca.getText();
            tipo=cmb_tipo.getSelectedItem().toString();
            codice=txt_codice.getText();
            pezzi=Integer.parseInt(cmb_pezzi.getSelectedItem().toString());
            if(strumenti!=null)
                for(int p=0;p<strumenti.size() && !trovo;p++){
                    sr=(Strumento)strumenti.get(p);
                    if(sr.codice.equals(txt_codice.getText()))
                        trovo=true;
                }
            if(spartiti!=null)
                for(int p=0;p<spartiti.size();p++){
                    sp=(Spartito)spartiti.get(p);
                    if(sp.codice.equals(txt_codice.getText()))
                        pezzi=sp.pezzi+Integer.parseInt(cmb_pezzi.getSelectedItem().toString());
                }
            if(strumenti!=null)
                for(int p=0;p<strumenti.size() && !trovo;p++){
                    sr=(Strumento)strumenti.get(p);
                    if(sr.codice.equals(txt_codice.getText()))
                        trovo=true;
                }
            if(spartiti!=null)
                for(int p=0;p<spartiti.size() && !trovo;p++){
                    sp=(Spartito)spartiti.get(p);
                    if(sp.codice.equals(txt_codice.getText())){
                       trovo=true;
                    }
                }
            if(trovo)
                JOptionPane.showMessageDialog(this,"Codice già esistente","Errore",JOptionPane.WARNING_MESSAGE);
            else{
                try{
                    prezzo=Float.parseFloat(txt_prezzo.getText());
                }catch(NumberFormatException e){
                    x=true;
                    JOptionPane.showMessageDialog(this, "Hai inserito un prezzo non valido", "Errore", JOptionPane.ERROR_MESSAGE);
                    lbl_prezzo.setForeground(Color.red);
                }
                if(!x){
                    if(rbt_strumento.isSelected()){
                        if(strumenti==null)
                            strumenti=new ArrayList();
                        modello=txt_modello.getText();
                        if(rbt_nuovo.isSelected()){
                            qual=rbt_nuovo.getText();
                        }else{
                            if(rbt_a.isSelected())
                                qual=rbt_usato.getText()+" "+rbt_a.getText();
                            else
                                if(rbt_b.isSelected())
                                    qual=rbt_usato.getText()+" "+rbt_b.getText();
                                else
                                    if(rbt_c.isSelected())
                                        qual=rbt_usato.getText()+" "+rbt_c.getText();
                        }
                        str=new Strumento(tipo,marca,modello,qual,codice,pezzi,prezzo);
                        strumenti.add(str);
                    }else{
                        if(strumenti!=null)
                            for(int p=0;p<spartiti.size() && !trovo;p++){
                                sp=(Spartito)spartiti.get(p);
                                if(sp.codice.equals(txt_codice.getText()))
                                    trovo=true;
                            }
                        
                        if(spartiti==null)
                            spartiti=new ArrayList();
                        autore=ControlliConv.convertinome(txt_autore.getText());
                        titolo=ControlliConv.convertinome(txt_titolo.getText());
                        spar=new Spartito(marca,tipo,autore,titolo,codice,pezzi,prezzo);
                        spartiti.add(spar);
                        }
                    }
                    JOptionPane.showMessageDialog(this, "Registrazione effettuata", "Successo", JOptionPane.INFORMATION_MESSAGE);
                }
        }
    }//GEN-LAST:event_btn_registraActionPerformed

