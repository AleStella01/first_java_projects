    private void btn_esciActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_esciActionPerformed
        // TODO add your handling code here:
        int n=JOptionPane.showConfirmDialog(this,"Salvare le modifiche?","Attenzione",JOptionPane.YES_NO_CANCEL_OPTION,JOptionPane.WARNING_MESSAGE);
        if(n==JOptionPane.YES_OPTION){

                try{
                    FileOutputStream futenti = new FileOutputStream("utenti.dat");
                    ObjectOutputStream sutenti = new ObjectOutputStream(futenti);
                    sutenti.writeObject(utenti);
                    sutenti.flush();
                }catch(IOException e){
                    JOptionPane.showMessageDialog(this,"Errore:" + e.getMessage(),"Errore scrittura file utenti",JOptionPane.ERROR_MESSAGE);
                }
            

                try{
                    FileOutputStream fstrumenti = new FileOutputStream("strumenti.dat");
                    ObjectOutputStream sstrumenti = new ObjectOutputStream(fstrumenti);
                    sstrumenti.writeObject(strumenti);
                    sstrumenti.flush();
                }catch(IOException e){
                    JOptionPane.showMessageDialog(this,"Errore:" + e.getMessage(),"Errore scrittura file strumenti",JOptionPane.ERROR_MESSAGE);
                }

                try{
                    FileOutputStream fspartiti = new FileOutputStream("spartiti.dat");
                    ObjectOutputStream sspartiti = new ObjectOutputStream(fspartiti);
                    sspartiti.writeObject(spartiti);
                    sspartiti.flush();
                }catch(IOException e){
                    JOptionPane.showMessageDialog(this,"Errore:" + e.getMessage(),"Errore scrittura file spartiti",JOptionPane.ERROR_MESSAGE);
                }
            
        }
        if(n==JOptionPane.CANCEL_OPTION){
            
        }else
            this.dispose();
    }//GEN-LAST:event_btn_esciActionPerformed

