    public Accesso() {
        initComponents();
        if(utentif.exists()){
            try{
                FileInputStream futenti = new FileInputStream("utenti.dat");
                ObjectInputStream sutenti = new ObjectInputStream(futenti);
                while(true){
                    try{
                        utenti=((ArrayList)sutenti.readObject());
                    }catch(IOException | ClassNotFoundException e){
                        break;
                    }
                }
            }catch(IOException e){
                JOptionPane.showMessageDialog(this,"ERROR" + e.getMessage(),"Errore lettura file utenti",JOptionPane.ERROR_MESSAGE);
            }
        }
        if(strumentif.exists()){
            try{
                FileInputStream fstrumenti = new FileInputStream("strumenti.dat");
                ObjectInputStream sstrumenti = new ObjectInputStream(fstrumenti);
                while(true){
                    try{
                        strumenti=((ArrayList)sstrumenti.readObject());
                    }catch(IOException | ClassNotFoundException e){
                        break;
                    }
                }
            }catch(IOException e){
                JOptionPane.showMessageDialog(this,"ERROR" + e.getMessage(),"Errore lettura file strumenti",JOptionPane.ERROR_MESSAGE);
            }
        }
        if(spartitif.exists()){
            try{
                FileInputStream fspartiti = new FileInputStream("spartiti.dat");
                ObjectInputStream sspartiti = new ObjectInputStream(fspartiti);
                while(true){
                    try{
                        spartiti=((ArrayList)sspartiti.readObject());
                    }catch(IOException | ClassNotFoundException e){
                        break;
                    }
                }
            }catch(IOException e){
                JOptionPane.showMessageDialog(this,"ERROR" + e.getMessage(),"Errore lettura file spartiti",JOptionPane.ERROR_MESSAGE);
            }
        }
    }

