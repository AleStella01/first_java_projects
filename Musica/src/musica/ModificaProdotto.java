    private void btn_cercaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cercaActionPerformed
        // TODO add your handling code here:
        boolean trovo = false;

        if (txt_ins.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Inserire un codice prodotto!", "Errore", JOptionPane.ERROR_MESSAGE);
        } else {
            for (i = 0; i < strumenti.size() && !trovo; i++) {
                strumento = (Strumento) strumenti.get(i);
                if (txt_ins.getText().equals(strumento.codice)) {
                    trovo = true;
                }
            }
            if (!trovo) {
                JOptionPane.showMessageDialog(this, "Prodotto non trovato!", "Errore", JOptionPane.ERROR_MESSAGE);
            } else {
                txt_ins.setText(null);
                txt_codice.setText(strumento.codice);
                txt_marca.setText(strumento.marca);
                txt_modello.setText(strumento.modello);
                txt_pezzi.setText(String.valueOf(strumento.pezzi));
                txt_prezzo.setText(String.valueOf(strumento.prezzo));
                txt_qual.setText(strumento.qualita);
                txt_tipo.setText(strumento.tipo);
                lbl_strumento.setIcon(new ImageIcon("src\\images\\strumenti\\"+strumento.tipo +".png"));
                btn_modifica.setEnabled(true);
                btn_acquista.setEnabled(true);
                btn_elimina.setEnabled(true);
            }
        }
    }//GEN-LAST:event_btn_cercaActionPerformed

