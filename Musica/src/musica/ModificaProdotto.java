    private void btn_fattoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_fattoActionPerformed
        // TODO add your handling code here:
        boolean vuoto=false, trovo=false;
        Strumento s;
        Spartito sp;
        int pezzi;
        float prezzo;
        if (txt_tipo.getText().isEmpty())
            vuoto=true;
        else
            if(ControlliConv.controllanome(txt_tipo.getText()))
                vuoto=true;
        if(txt_marca.getText().isEmpty())
            vuoto=true;
        if(txt_modello.getText().isEmpty())
            vuoto=true;
        if(txt_qual.getText().isEmpty())
            vuoto=true;
        else
            if(ControlliConv.controllanome(txt_qual.getText()))
                vuoto=true;
            else
                if(!(txt_qual.getText().equals("Nuovo") || txt_qual.getText().equals("Usato A") || txt_qual.getText().equals("Usato B")|| txt_qual.getText().equals("Usato C")))
                    vuoto=true;
        if(txt_codice.getText().isEmpty())
            vuoto=true;
        if(txt_pezzi.getText().isEmpty())
            vuoto=true;
        if(txt_prezzo.getText().isEmpty())
            vuoto=true;
        try{
            pezzi=Integer.parseInt(txt_pezzi.getText());
            prezzo=Float.parseFloat(txt_prezzo.getText());
        }catch(NumberFormatException e){
            vuoto=true;
        }
        if(strumenti!=null)
                for(int x=0;x<strumenti.size() && !trovo;x++){
                    s=(Strumento)strumenti.get(x);
                    if(s.codice.equals(txt_codice.getText()))
                        trovo=true;
                }
        if(spartiti!=null)
            for(int x=0;x<spartiti.size();x++){
                sp=(Spartito)spartiti.get(x);
                if(sp.codice.equals(txt_codice.getText())){
                    trovo=true;
                    vuoto=true;
                }
            }
        if(trovo)
            JOptionPane.showMessageDialog(this,"Codice già esistente","Errore",JOptionPane.WARNING_MESSAGE);
        if(vuoto)
            JOptionPane.showMessageDialog(this,"Impossibile effettuare l'operazione, mancano dati","Errore",JOptionPane.ERROR_MESSAGE);
        else{
            strumenti.remove(i-1);
            if(!(strumenti==null)){
                for(int i=0;i<strumenti.size() && !trovo;i++){
                    s=(Strumento)strumenti.get(i);
                    if(s.codice.equals(txt_codice.getText()))
                        trovo=true;
                }
            }if(!trovo){
                if (!(strumento.codice.equals(txt_codice.getText()))) {
                    strumento.codice = txt_codice.getText();
                }
                if (!(strumento.marca.equals(txt_marca.getText()))) {
                    strumento.marca = txt_marca.getText();
                }
                if (!(strumento.modello.equals(txt_modello.getText()))) {
                    strumento.modello = txt_modello.getText();
                }
                if (!(strumento.pezzi == Integer.parseInt(txt_pezzi.getText()))) {
                    strumento.pezzi = Integer.parseInt(txt_pezzi.getText());
                }
                if (!(strumento.prezzo == Float.parseFloat(txt_prezzo.getText()))) {
                    strumento.prezzo = Float.parseFloat(txt_prezzo.getText());
                }
                if (!(strumento.qualita.equals(txt_qual.getText()))) {
                    strumento.qualita = txt_qual.getText();
                }
                if (!(strumento.tipo.equals(txt_tipo.getText()))) {
                    strumento.tipo = txt_tipo.getText();
                }
                strumenti.add(i - 1, strumento);
                lbl_strumento.setIcon(new ImageIcon("src\\images\\strumenti\\" + strumento.tipo + ".png"));
                txt_tipo.setEnabled(false);
                txt_tipo.setText(strumento.tipo);
                txt_marca.setEnabled(false);
                txt_marca.setText(strumento.marca);
                txt_modello.setEnabled(false);
                txt_modello.setText(strumento.modello);
                txt_qual.setEnabled(false);
                txt_qual.setText(strumento.qualita);
                txt_codice.setEnabled(false);
                txt_codice.setText(strumento.codice);
                txt_pezzi.setEnabled(false);
                txt_pezzi.setText(String.valueOf(strumento.pezzi));
                txt_prezzo.setEnabled(false);
                txt_prezzo.setText(String.valueOf(strumento.prezzo));
                btn_modifica.setEnabled(true);
                btn_annulla.setEnabled(false);
                btn_elimina.setEnabled(true);
                btn_fatto.setEnabled(false);
                modificato = true;
            }else{
                JOptionPane.showMessageDialog(this,"Codice prodotto già esistente","Errore",JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btn_fattoActionPerformed

