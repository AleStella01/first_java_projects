    private void btn_registraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_registraActionPerformed
        // TODO add your handling code here:
        Utente u=null;
        String nome, cognome, cod_f, via, num_c, citta, data_n, potere, user, password;
        char sesso;
        boolean vuoto = false, trovo=false, x=false;
        
        lbl_nome.setForeground(Color.black);
        lbl_cognome.setForeground(Color.black);
        lbl_codF.setForeground(Color.black);
        lbl_sesso.setForeground(Color.black);
        lbl_via.setForeground(Color.black);
        lbl_nc.setForeground(Color.black);
        lbl_citta.setForeground(Color.black);
        lbl_data.setForeground(Color.black);
        lbl_user.setForeground(Color.black);
        lbl_password.setForeground(Color.black);
        lbl_psw2.setForeground(Color.black);
        lbl_poteri.setForeground(Color.black);
        if(txt_nome.getText().isEmpty()){
            vuoto=true;
            lbl_nome.setForeground(Color.red);
        }else{
            if(ControlliConv.controllanome(txt_nome.getText())){
                vuoto=true;
                lbl_nome.setForeground(Color.red);
            }
        }
        if(txt_cognome.getText().isEmpty()){
            vuoto=true;
            lbl_cognome.setForeground(Color.red);
        }else{
            if(ControlliConv.controllanome(txt_cognome.getText())){
                vuoto=true;
                lbl_cognome.setForeground(Color.red);
            }
        }
        if(txt_codF.getText().isEmpty()){
            vuoto=true;
            lbl_codF.setForeground(Color.red);
        }
        if(rbt_maschio.isSelected() == false && rbt_femmina.isSelected() == false){
            vuoto=true;
            lbl_sesso.setForeground(Color.red);
        }
        if(txt_via.getText().isEmpty()){
            vuoto=true;
            lbl_residenza.setForeground(Color.red);
            lbl_via.setForeground(Color.red);
        }else{
            if(ControlliConv.controllanome(txt_via.getText())){
                vuoto=true;
                lbl_via.setForeground(Color.red);
            }
        }
        if(txt_nc.getText().isEmpty()){
            vuoto=true;
            lbl_nc.setForeground(Color.red);
            lbl_residenza.setForeground(Color.red);
        }else{
            if(ControlliConv.controllacivico(txt_nc.getText())){
                vuoto=true;
                lbl_nc.setForeground(Color.red);
            }
        }
        if(txt_citta.getText().isEmpty()){
            vuoto=true;
            lbl_citta.setForeground(Color.red);
            lbl_residenza.setForeground(Color.red);
        }else{
            if(ControlliConv.controllanome(txt_citta.getText())){
                vuoto=true;
                lbl_citta.setForeground(Color.red);
            }
        }
        if(cln_dataN.getDate()==null){
            vuoto=true;
            lbl_data.setForeground(Color.red);
        }
        if(rbt_cliente.isSelected()==false && rbt_amministratore.isSelected()==false && rbt_dipendente.isSelected()==false){
            vuoto=true;
            lbl_poteri.setForeground(Color.red);
        }
        if(txt_user.getText().isEmpty()){
            vuoto=true;
            lbl_user.setForeground(Color.red);
        }
        if(psw_password.getText().isEmpty() || psw_password2.getText().isEmpty()){
            vuoto=true;
            lbl_password.setForeground(Color.red);
            lbl_psw2.setForeground(Color.red);
        }
        if(!(utenti==null))//Non sono stati inseriti utenti
            for(int i=0;i<utenti.size() && !trovo;i++){
                u=(Utente)utenti.get(i);
                if(txt_codF.getText().equals(u.cod_f))
                    trovo=true;
                if(txt_user.getText().equals(u.utente))
                    x=true;
            }
        if (trovo)
            JOptionPane.showMessageDialog(this, "Codice fiscale già esistente!", "Errore", JOptionPane.ERROR_MESSAGE);
        else
            if(x)
                JOptionPane.showMessageDialog(this, "User name già esistente!", "Errore", JOptionPane.ERROR_MESSAGE);
            else
                if(vuoto)
                    JOptionPane.showMessageDialog(this, "Non è possibile effettuare la registazione, mancono alcune informazioni", "Errore", JOptionPane.ERROR_MESSAGE);
                else{
                    if(!(psw_password.getText().equals(psw_password2.getText()))){
                        lbl_password.setForeground(Color.red);
                        lbl_psw2.setForeground(Color.red);
                        psw_password.setForeground(Color.red);
                        psw_password2.setForeground(Color.red);
                        JOptionPane.showMessageDialog(this, "Le password non coincidono!", "Errore", JOptionPane.ERROR_MESSAGE);
                    }else{
                        nome=ControlliConv.convertinome(txt_nome.getText());
                        cognome=ControlliConv.convertinome(txt_cognome.getText());
                        via=ControlliConv.convertinome(txt_via.getText());
                        num_c=txt_nc.getText();
                        citta=ControlliConv.convertinome(txt_citta.getText());
                        user=txt_user.getText();
                        password=psw_password.getText();
                        if(rbt_maschio.isSelected()){
                            sesso=rbt_maschio.getText().charAt(0);
                        }
                        else{
                            sesso=rbt_femmina.getText().charAt(0);
                        }
                        DateFormat df= new SimpleDateFormat("dd-MM-yyyy");
                        data_n=df.format(cln_dataN.getDate());
                        if(rbt_cliente.isSelected()){
                            potere=rbt_cliente.getText();
                        }
                        else{
                            if(rbt_dipendente.isSelected()){
                                potere=rbt_dipendente.getText();
                            }
                            else
                                potere=rbt_amministratore.getText();
                        }
                        cod_f=txt_codF.getText().toUpperCase();
                        if(ControlliConv.controllacodice(cod_f)){
                            JOptionPane.showMessageDialog(this, "Hai inserito un codice fiscale non valido!", "Errore", JOptionPane.ERROR_MESSAGE);
                            lbl_codF.setForeground(Color.red);
                        }else{
                            u=new Utente(user,password,potere,cod_f,nome,cognome,sesso,via,num_c,citta,data_n);
                            if(utenti==null)
                                utenti=new ArrayList();
                            utenti.add(u);
                            JOptionPane.showMessageDialog(this, "Registrazione effettuata!", "Successo!", JOptionPane.INFORMATION_MESSAGE);
                            txt_nome.setText(null);
                            txt_cognome.setText(null);
                            txt_codF.setText(null);
                            rbt_maschio.setSelected(false);
                            rbt_femmina.setSelected(false);
                            txt_via.setText(null);
                            txt_nc.setText(null);
                            txt_citta.setText(null);
                            cln_dataN.setDate(null);
                            txt_user.setText(null);
                            psw_password.setText(null);
                            psw_password2.setText(null);
                            rbt_cliente.setSelected(false);
                            rbt_dipendente.setSelected(false);
                            rbt_amministratore.setSelected(false);
                        }
                    }
            
        }
    }//GEN-LAST:event_btn_registraActionPerformed

