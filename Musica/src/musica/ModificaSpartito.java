    private void btn_cercaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cercaActionPerformed
        // TODO add your handling code here:
        boolean trovo=false;
        
        if(txt_ins.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Inserire un codice prodotto!", "Errore", JOptionPane.ERROR_MESSAGE);
        }else{
            for(i=0;i<spartiti.size()&&!trovo;i++){
                spartito=(Spartito) spartiti.get(i);
                if(txt_ins.getText().equals(spartito.codice))
                    trovo=true;
            }
            if(!trovo){
                JOptionPane.showMessageDialog(this, "Utente non trovato!", "Errore", JOptionPane.ERROR_MESSAGE);
            }else{
                txt_ins.setText(null);
                txt_marca.setText(spartito.marca);
                txt_strumento.setText(spartito.tipo);
                txt_autore.setText(spartito.autore);
                txt_titolo.setText(spartito.titolo);
                txt_codice.setText(spartito.codice);
                txt_pezzi.setText(String.valueOf(spartito.pezzi));
                txt_prezzo.setText(String.valueOf(spartito.prezzo));
                lbl_strumento.setIcon(new ImageIcon("src\\images\\strumenti\\"+spartito.autore+".png"));
                btn_modifica.setEnabled(true);
                btn_acquista.setEnabled(true);
                btn_elimina.setEnabled(true);
                btn_annulla.setEnabled(false);
                btn_fatto.setEnabled(false);
            }
        }
    }//GEN-LAST:event_btn_cercaActionPerformed

    private void btn_acquistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_acquistaActionPerformed
        // TODO add your handling code here:
        boolean errore;
        int n = 0;
        try {
            do {
                errore=false;
                n = Integer.parseInt(JOptionPane.showInputDialog(this, "Quanti prodotti vuoi acquistare", "Rispondi", JOptionPane.INFORMATION_MESSAGE));
                if (n > spartito.pezzi || n<0) {
                    errore = true;
                    JOptionPane.showMessageDialog(this, "Inserire un valore valido!", "Errore", JOptionPane.ERROR_MESSAGE);
                }else{
                    spartito.pezzi = spartito.pezzi - n;
                    spartiti.remove(i-1);
                    spartiti.add(i-1,spartito);
                    txt_pezzi.setText(String.valueOf(spartito.pezzi));
                    JOptionPane.showMessageDialog(this,"Operazione effettuata! \n Importo: "+(spartito.prezzo*n),"OK",JOptionPane.INFORMATION_MESSAGE);
                }
            } while (errore);
        } catch (HeadlessException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Inserire un valore accettabile", "Errore", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_acquistaActionPerformed

