    private void btn_fattoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_fattoActionPerformed
        // TODO add your handling code here:
       boolean vuoto=false, trovo=false;
        Strumento s;
        Spartito sp;
        int pezzi;
        float prezzo;
        
        if(txt_strumento.getText().isEmpty()){
            vuoto=true;
        }else{
            if(ControlliConv.controllanome(txt_strumento.getText()))
                vuoto=true;
        }
        if(txt_autore.getText().isEmpty()){
            vuoto=true;
        }else
            if(ControlliConv.controllanome(txt_autore.getText()))
                vuoto=true;
        if(txt_titolo.getText().isEmpty())
            vuoto=true;
        else
            if(ControlliConv.controllanome(txt_titolo.getText()))
                vuoto=true;
        
        if(txt_marca.getText().isEmpty())
            vuoto=true;
        if(txt_codice.getText().isEmpty())
            vuoto=true;
        if(txt_pezzi.getText().isEmpty())
            vuoto=true;
        if(txt_prezzo.getText().isEmpty())
            vuoto=true;
        try{
            pezzi=Integer.parseInt(txt_pezzi.getText());
            prezzo=Float.parseFloat(txt_prezzo.getText());
        }catch(NumberFormatException e){
            vuoto=true;
        }
        if(strumenti!=null)
                for(int x=0;x<strumenti.size() && !trovo;x++){
                    s=(Strumento)strumenti.get(x);
                    if(s.codice.equals(txt_codice.getText()))
                        trovo=true;
                }
        if(spartiti!=null){
            spartiti.remove(i-1);
            for(int x=0;x<spartiti.size();x++){
                sp=(Spartito)spartiti.get(x);
                if(sp.codice.equals(txt_codice.getText())){
                    trovo=true;
                    vuoto=true;
                }
            }
        }
        if(trovo)
            JOptionPane.showMessageDialog(this,"Codice già esistente","Errore",JOptionPane.WARNING_MESSAGE);
        if(vuoto)
            JOptionPane.showMessageDialog(this,"Impossibile effettuare l'operazione, mancano dati","Errore",JOptionPane.ERROR_MESSAGE);
        else{
                if (!(spartito.codice.equals(txt_codice.getText()))) {
                    spartito.codice = txt_codice.getText();
                }
                if (!(spartito.marca.equals(txt_marca.getText()))) {
                    spartito.marca = txt_marca.getText();
                }
                if (!(spartito.pezzi == Integer.parseInt(txt_pezzi.getText()))) {
                    spartito.pezzi = Integer.parseInt(txt_pezzi.getText());
                }
                if (!(spartito.prezzo == Float.parseFloat(txt_prezzo.getText()))) {
                    spartito.prezzo = Float.parseFloat(txt_prezzo.getText());
                }
                if (!(spartito.tipo.equals(txt_strumento.getText()))) {
                    spartito.tipo = txt_strumento.getText();
                }
                spartiti.add(i - 1, spartiti);
                lbl_strumento.setIcon(new ImageIcon("src\\images\\strumenti\\"+spartito.autore+".png"));
                txt_marca.setEnabled(false);
                txt_marca.setText(spartito.marca);
                txt_strumento.setEnabled(false);
                txt_strumento.setText(spartito.tipo);
                txt_autore.setEnabled(false);
                txt_autore.setText(spartito.autore);
                txt_titolo.setEnabled(false);
                txt_titolo.setText(spartito.titolo);
                txt_codice.setEnabled(false);
                txt_codice.setText(spartito.codice);
                txt_pezzi.setEnabled(false);
                txt_pezzi.setText(String.valueOf(spartito.pezzi));
                txt_prezzo.setEnabled(false);
                txt_prezzo.setText(String.valueOf(spartito.prezzo));
                btn_modifica.setEnabled(true);
                btn_annulla.setEnabled(false);
                btn_elimina.setEnabled(true);
                btn_fatto.setEnabled(false);
        }
    }//GEN-LAST:event_btn_fattoActionPerformed

