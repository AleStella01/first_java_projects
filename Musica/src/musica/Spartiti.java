    public void creaSlider(){
        Hashtable etichette= new Hashtable();
        
        for(int x=0;x<=100;x=x+10){
            etichette.put(new Integer(x), new Etichetta(String.valueOf(x)));
        }
        sld_volume.setLabelTable(etichette);
    }

