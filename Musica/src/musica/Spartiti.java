    private void btn_cercaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cercaActionPerformed
        // TODO add your handling code here:
        int i;
        boolean trovo=false;
        DefaultTableModel model=(DefaultTableModel) tbl_spartiti.getModel();
        Object rowData[]=new Object[5];
        if(txt_autore.getText().isEmpty())
            JOptionPane.showMessageDialog(this,"Inserire nome autore!","Errore",JOptionPane.ERROR_MESSAGE);
        else{
            for(int a=0; a<model.getRowCount();){
                model.removeRow(0);
            }
            for(i=0;i<spartiti.size();i++){
                s=(Spartito)spartiti.get(i);
                if(txt_autore.getText().equals(s.autore)){
                    trovo=true;
                    rowData[0]=s.autore;
                    rowData[1]=s.titolo;
                    rowData[2]=s.tipo;
                    rowData[3]=s.codice;
                    rowData[4]=s.prezzo;
                    model.addRow(rowData);
                }
            }
            if(!trovo)
                JOptionPane.showMessageDialog(this,"Non ho trovato nessuno spartito per l'autore indicato!","Errore",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_cercaActionPerformed

