    private void btn_indietroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_indietroActionPerformed
        // TODO add your handling code here:
        i--;
        if(i<0){
            JOptionPane.showMessageDialog(this,"Non ci sono più strumenti","errore",JOptionPane.ERROR_MESSAGE);
            btn_indietro.setEnabled(false);
        }
        else{
            visualizza(i);
        }
        btn_avanti.setEnabled(true);
    }//GEN-LAST:event_btn_indietroActionPerformed

    private void btn_avantiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_avantiActionPerformed
        // TODO add your handling code here:
        i++;
        if(i>=strumenti.size()){
            JOptionPane.showMessageDialog(this,"Non ci sono più strumenti","errore",JOptionPane.ERROR_MESSAGE);
            btn_avanti.setEnabled(false);
        }else{
            visualizza(i);
        }
        btn_indietro.setEnabled(true);
    }//GEN-LAST:event_btn_avantiActionPerformed

